#!/bin/sh
# Writes BundleDigests.swift for VersionPlugin: the sha256 of every file in the resource bundle, keyed by its
# path inside the bundle, so the binary refuses a resource that was changed after install. One shasum run.
# Usage: scripts/bundle-digests.sh <output BundleDigests.swift> <package directory>
set -eu

out="${1:?usage: bundle-digests.sh <output> <package dir>}"
package="${2:?usage: bundle-digests.sh <output> <package dir>}"
resources="${package}/Sources/Offsider/Resources"

[ -d "$resources" ] || { echo "bundle-digests.sh: no resources at ${resources}" >&2; exit 1; }

entries="$(cd "$resources" && find . -type f ! -path '*/xcuserdata/*' ! -name .DS_Store -print0 \
  | LC_ALL=C sort -z | xargs -0 /usr/bin/shasum -a 256 \
  | sed -E 's|^([0-9a-f]{64})  \./(.*)$|        "\2": "\1",|')"

content="// Auto-generated by VersionPlugin from Sources/Offsider/Resources; never edit.
enum BundleDigests {
    /// sha256 of every file in the resource bundle, keyed by its path inside the bundle.
    static let files: [String: String] = [
${entries}
    ]
}"

if [ -f "$out" ] && [ "$(cat "$out")" = "$content" ]; then
  exit 0
fi
mkdir -p "$(dirname "$out")"
tmp="${out}.tmp.$$"
printf '%s\n' "$content" > "$tmp"
mv -f "$tmp" "$out"
