#!/bin/sh
# Writes Version.swift for VersionPlugin: OFFSIDER_VERSION, else `git describe`, else dev; the file changes only when the version does.
# Usage: scripts/version-stamp.sh <output Version.swift> <package directory>
set -eu

out="${1:?usage: version-stamp.sh <output> <package dir>}"
package="${2:?usage: version-stamp.sh <output> <package dir>}"

version="${OFFSIDER_VERSION:-}"
if [ -z "$version" ] && [ -x /usr/bin/git ]; then
  version="$(/usr/bin/git --no-optional-locks -C "$package" describe --tags --always --dirty 2>/dev/null || true)"
fi
version="$(printf '%s' "$version" | LC_ALL=C tr -cd 'A-Za-z0-9._+-')"
[ -n "$version" ] || version=dev

content="// Auto-generated by VersionPlugin
let VERSION = \"${version}\""

if [ -f "$out" ] && [ "$(cat "$out")" = "$content" ]; then
  exit 0
fi
mkdir -p "$(dirname "$out")"
tmp="${out}.tmp.$$"
printf '%s\n' "$content" > "$tmp"
mv -f "$tmp" "$out"
