import Foundation
import OffsiderCore
import Testing

@Suite("version-stamp script")
struct VersionStampScriptTests {
    static let script = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().appendingPathComponent("scripts/version-stamp.sh").path

    /// Git with no user or system config, so a developer's signing or hooks never apply.
    static let gitEnvironment: [String: String] = {
        var environment = ProcessInfo.processInfo.environment
        environment["GIT_CONFIG_GLOBAL"] = "/dev/null"
        environment["GIT_CONFIG_NOSYSTEM"] = "1"
        environment.removeValue(forKey: "OFFSIDER_VERSION")
        return environment
    }()

    static func directory() throws -> URL {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent("offsider-stamp-\(UUID().uuidString)").resolvingSymlinksInPath()
        try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    @discardableResult
    static func git(_ arguments: [String], in directory: URL) async throws -> String {
        let result = try await ProcessCapture.run(
            executable: "/usr/bin/git",
            arguments: ["-C", directory.path, "-c", "user.name=Offsider Test", "-c", "user.email=test@example.com", "-c", "commit.gpgsign=false"] + arguments,
            environment: gitEnvironment,
            timeout: 30
        )
        #expect(result.status == 0, "git \(arguments.joined(separator: " ")): \(result.stderr)")
        return result.stdout.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// A repository with one commit tagged v1.2.3.
    static func taggedRepository() async throws -> URL {
        let repo = try directory()
        try await git(["init", "-q"], in: repo)
        try Data("one\n".utf8).write(to: repo.appendingPathComponent("file.txt"))
        try await git(["add", "file.txt"], in: repo)
        try await git(["commit", "-q", "-m", "first"], in: repo)
        try await git(["tag", "v1.2.3"], in: repo)
        return repo
    }

    /// Runs the script for `package` and returns the version it wrote.
    static func stamp(_ package: URL, into output: URL, environment extra: [String: String] = [:]) async throws -> String {
        let result = try await ProcessCapture.run(
            executable: "/bin/sh", arguments: [script, output.path, package.path], environment: gitEnvironment.merging(extra) { $1 }, timeout: 30
        )
        #expect(result.status == 0, "\(result.stderr)")
        let text = try String(contentsOf: output, encoding: .utf8)
        #expect(text.hasPrefix("// Auto-generated by VersionPlugin\nlet VERSION = \""))
        return String(text.split(separator: "\"")[1])
    }

    @Test("OFFSIDER_VERSION wins over git, and only letters, digits and . _ + - survive")
    func environmentOverride() async throws {
        let repo = try await Self.taggedRepository()
        defer { try? FileManager.default.removeItem(at: repo) }
        let output = repo.appendingPathComponent("out/Version.swift")

        #expect(try await Self.stamp(repo, into: output, environment: ["OFFSIDER_VERSION": "2.0.0-rc.1"]) == "2.0.0-rc.1")
        #expect(try await Self.stamp(repo, into: output, environment: ["OFFSIDER_VERSION": "1.0\" + $(evil)\n"]) == "1.0+evil")
    }

    @Test("git describe follows the tag, an edit and a new commit")
    func followsGit() async throws {
        let repo = try await Self.taggedRepository()
        defer { try? FileManager.default.removeItem(at: repo) }
        let output = try Self.directory().appendingPathComponent("Version.swift")

        #expect(try await Self.stamp(repo, into: output) == "v1.2.3")
        try Data("two\n".utf8).write(to: repo.appendingPathComponent("file.txt"))
        #expect(try await Self.stamp(repo, into: output) == "v1.2.3-dirty")
        try await Self.git(["commit", "-q", "-am", "second"], in: repo)
        let head = try await Self.git(["rev-parse", "--short", "HEAD"], in: repo)
        #expect(try await Self.stamp(repo, into: output) == "v1.2.3-1-g\(head)")
    }

    @Test("a git worktree, whose HEAD lives under the main repository, gets its own commit")
    func worktree() async throws {
        let repo = try await Self.taggedRepository()
        defer { try? FileManager.default.removeItem(at: repo) }
        let worktree = repo.appendingPathComponent("wt")
        try await Self.git(["worktree", "add", "-q", "-b", "feat/other", worktree.path], in: repo)
        try Data("three\n".utf8).write(to: worktree.appendingPathComponent("file.txt"))
        try await Self.git(["commit", "-q", "-am", "in the worktree"], in: worktree)
        let head = try await Self.git(["rev-parse", "--short", "HEAD"], in: worktree)

        #expect(try await Self.stamp(worktree, into: repo.appendingPathComponent("out/Version.swift")) == "v1.2.3-1-g\(head)")
        #expect(try await Self.stamp(repo, into: repo.appendingPathComponent("out/Main.swift")) == "v1.2.3")
    }

    @Test("outside a repository the version is dev")
    func noRepository() async throws {
        let plain = try Self.directory()
        defer { try? FileManager.default.removeItem(at: plain) }
        #expect(try await Self.stamp(plain, into: plain.appendingPathComponent("Version.swift"), environment: ["GIT_CEILING_DIRECTORIES": plain.deletingLastPathComponent().path]) == "dev")
    }

    @Test("an unchanged version leaves the file untouched, so the module is not rebuilt")
    func keepsModificationDate() async throws {
        let repo = try await Self.taggedRepository()
        defer { try? FileManager.default.removeItem(at: repo) }
        let output = repo.appendingPathComponent("out/Version.swift")
        _ = try await Self.stamp(repo, into: output)
        let past = Date(timeIntervalSince1970: 1_700_000_000)
        try FileManager.default.setAttributes([.modificationDate: past], ofItemAtPath: output.path)

        _ = try await Self.stamp(repo, into: output)
        #expect(try FileManager.default.attributesOfItem(atPath: output.path)[.modificationDate] as? Date == past)

        _ = try await Self.stamp(repo, into: output, environment: ["OFFSIDER_VERSION": "3.0.0"])
        #expect(try FileManager.default.attributesOfItem(atPath: output.path)[.modificationDate] as? Date != past)
    }
}
